/// Frozen read-only input for supplementary documentation renderers. Canonical
/// resources, original locations and the derived display document remain
/// separate. No output directory/write capability is acquired by this object.
class DocumentationPresentation {
  DocumentationPresentation._(this._owner, this._captured, this._display)
    : originalProjection = _display.original,
      projection = _display.projection,
      _sources = _display.sources;
  final BusyProject _owner;
  final _CheckedInput _captured;
  final _PreparedReferenceDisplay _display;
  final _DocumentationSourceIndex _sources;
  final Map<String, dynamic> originalProjection, projection;
  AnalysisSnapshot get snapshot => _captured.snapshot;

  /// Read-only JSON coordinates for renderer presentation. This is NOT a
  /// bundled API/schema resource and must not be evaluated as one.
  AnalysisSnapshot get displayCoordinates => _display.coordinates;
  String get text => _display.result['output']['text'] as String;
  String get identity => _display.result['output']['identity'] as String;
  bool get unsaved => _captured.checked['unsaved'] == true;
  bool get saved => _captured.saved;

  /// Equal filenames/content do not transfer a captured owner's authority to
  /// another project instance or a reopened workspace.
  bool belongsTo(BusyProject project) => identical(_owner, project);
  bool get outdated =>
      _owner._closed ||
      _captured.revision != _owner._resourceRevision ||
      !snapshot.current(_owner.store);
  List get sourceProvenance => _display.result['provenance'] as List;

  List<DocumentationSourceAction> get sourceActions => _sources.actions;

  DocumentationSourceAction? sourceActionFor(
    String pointer, {
    String role = 'node',
  }) {
    final index = _sources.coordinates[jsonEncode([role, pointer])];
    return index == null ? null : sourceActions[index];
  }

  /// Validate at the point of navigation, not only when a window was opened.
  /// An old window cannot retarget a moved/reloaded source or a newer root.
  DocumentationSourceAction resolveSourceAction(int index) {
    if (outdated) {
      throw CoreFailure(
        'documentation.stale',
        'The documentation snapshot is outdated; reopen it before navigating',
      );
    }
    if (index < 0 || index >= sourceActions.length) {
      throw CoreFailure(
        'documentation.source',
        'The documentation source action is not part of this snapshot',
      );
    }
    return sourceActions[index];
  }

  // Original navigation locations stay with the native owner. Authored and
  // retained identifiers still belong to the authored values; none grants
  // retrieval permission. Exact source numbers stay in
  // JSON text, never a Dart decode/encode round trip.
  Map<String, Object?> toJson() => Map.unmodifiable({
    'version': 1,
    'producer': 'busyapi-documentation-presentation',
    'producerVersion': '1',
    'snapshot': snapshot.sourceIdentity,
    'contextSnapshot': snapshot.identity,
    'root': displayCoordinates.root,
    'representation': 'graph-addressed-display-only',
    'displayProducer': 'busyapi-reference-display',
    'displayProducerVersion': '1',
    'text': text,
    'identity': identity,
    'projection': projection,
    'sourceActions': List.unmodifiable(
      sourceActions.map((action) => action.toJson()),
    ),
    'input': unsaved ? 'working-copy' : 'saved-source',
    'unsaved': unsaved,
  });
}

extension _ContractDerivation on BusyProject {
  // Single-file bundle publication only. Read-only renderer coordinates do
  // not cross this semantic transformation boundary.
  Future<_PreparedContract> _deriveContract(
    _CheckedInput captured,
    String outputId, {
    String? requestId,
    bool Function()? cancelled,
  }) async {
    void active() {
      if (_closed || cancelled?.call() == true) {
        throw CoreFailure('cancelled', 'Bundle generation was cancelled');
      }
    }

    active();
    final snapshot = captured.snapshot;
    final result = await engine.request('deriveBundle', {
      ...snapshot.toJson(),
      'outputId': outputId,
    }, requestId: requestId == null ? null : '$requestId-bundle');
    active();
    final output = result['output'];
    if (result['version'] != 1 ||
        result['complete'] != true ||
        result['snapshot'] != snapshot.identity ||
        result['root'] != snapshot.root ||
        result['producer'] != 'busyapi-graph-bundle' ||
        result['producerVersion'] != '3' ||
        output is! Map ||
        output['id'] != outputId ||
        output['text'] is! String ||
        (output['text'] as String).length > 16 * 1024 * 1024 ||
        output['identity'] !=
            await textIdentityAsync(output['text'] as String) ||
        result['provenance'] is! List) {
      throw CoreFailure(
        'bundle.protocol',
        'The worker did not return a complete, source-bound bundle',
      );
    }
    active();
    final derived = AnalysisSnapshot(
      root: outputId,
      resources: [
        {
          'id': outputId,
          'text': output['text'],
          'identity': output['identity'],
          'generation': 0,
        },
      ],
      engineIdentity: engine.assetIdentity,
    );
    final evaluated = await engine.request(
      'evaluateSchemas',
      derived.toJson(),
      requestId: requestId == null ? null : '$requestId-bundle-schema',
    );
    BusyProject._verifySchemaEvaluation(evaluated, derived);
    if (evaluated['complete'] != true) {
      throw CoreFailure(
        'bundle.incomplete',
        'The derived schema evaluation did not complete',
      );
    }
    if ((evaluated['findings'] as List).any(
      (finding) => finding['severity'] == 'error',
    )) {
      throw CoreFailure(
        'bundle.proof',
        'Derived schemas failed their dialect checks',
      );
    }
    active();
    final resources = {
      for (final resource in snapshot.resources)
        resource['id'] as String: resource,
    };
    for (final entry in result['provenance'] as List) {
      if (entry is! Map ||
          entry['source'] is! Map ||
          entry['derived'] is! Map ||
          entry['source']['resource'] is! String ||
          entry['source']['pointer'] is! String ||
          !resources.containsKey(entry['source']['resource']) ||
          entry['derived']['resource'] != outputId ||
          entry['derived']['pointer'] is! String) {
        throw CoreFailure(
          'bundle.protocol',
          'The bundle source provenance is malformed',
        );
      }
      final source = entry['source'] as Map;
      final alias =
          source.containsKey('physicalPointer') ||
          source.containsKey('range') ||
          source.containsKey('occurrenceRange');
      if (alias) {
        final length =
            (resources[source['resource']]!['text'] as String).length;
        bool range(Object? value) =>
            value is List &&
            value.length == 2 &&
            value[0] is int &&
            value[1] is int &&
            (value[0] as int) >= 0 &&
            (value[1] as int) >= (value[0] as int) &&
            (value[1] as int) <= length;
        if (source['physicalPointer'] is! String ||
            !range(source['range']) ||
            !range(source['occurrenceRange'])) {
          throw CoreFailure(
            'bundle.protocol',
            'The bundle alias provenance is malformed',
          );
        }
      }
    }
    return _PreparedContract(derived, result);
  }
}

extension DocumentationBuild on BusyProject {
  /// The checked original graph supplies renderer coordinates independently of
  /// single-file bundling. There is no second resource loader/parser, schema
  /// evaluation of a disposable view, or output write capability here.
  Future<DocumentationPresentation> captureDocumentationPresentation(
    String root, {
    bool saved = false,
    String? requestId,
    bool Function()? cancelled,
    void Function(String resource)? onResourceRefreshed,
  }) async {
    final captured = await _captureCheckedInput(
      root,
      operation: 'documentation',
      saved: saved,
      requestId: requestId,
      cancelled: cancelled,
      onResourceRefreshed: onResourceRefreshed,
    );
    return _prepareDocumentationPresentation(
      captured,
      requestId: requestId,
      cancelled: cancelled,
    );
  }

  Future<DocumentationPresentation> _prepareDocumentationPresentation(
    _CheckedInput captured, {
    String? requestId,
    bool Function()? cancelled,
  }) async {
    void active() {
      if (_closed || cancelled?.call() == true) {
        throw CoreFailure('cancelled', 'Documentation capture was cancelled');
      }
    }

    final snapshot = captured.snapshot;
    final outputId =
        'https://busyapi-display.invalid/${snapshot.sourceIdentity}/reference.json';
    final result = await engine.request('referenceDisplay', {
      ...snapshot.toJson(),
      'outputId': outputId,
    }, requestId: requestId == null ? null : '$requestId-display');
    active();
    // Hashing, location verification, provenance joining and recursive freezing
    // are one bounded data-only worker operation. Large projections must not
    // repeatedly walk their entire trees on Flutter's input isolate.
    final display = await _runDocumentationWorker<_PreparedReferenceDisplay>(
      _documentationDisplayWorker,
      [result, snapshot, outputId, engine.assetIdentity],
      active,
    );
    active();
    return DocumentationPresentation._(this, captured, display);
  }

  /// One selected API root, approved immutable resources, no implicit network,
  /// display, Node renderer, or disk publication during generation.
  Future<DocumentationOutput> prepareDocumentation(
    String root,
    String destination, {
    String preset = 'native-reference',
    Map<String, String>? labels,
    bool saved = false,
    String? requestId,
    bool Function()? cancelled,
    void Function(String resource)? onResourceRefreshed,
  }) async {
    if (!['native-reference', 'redoc', 'swagger'].contains(preset)) {
      throw CoreFailure(
        'documentation.preset',
        'The requested documentation preset is not installed',
      );
    }
    final captured = await _captureOutputInput(
      root,
      destination,
      operation: 'documentation',
      saved: saved,
      requestId: requestId,
      cancelled: cancelled,
      onResourceRefreshed: onResourceRefreshed,
    );
    final snapshot = captured.snapshot;
    try {
      void active() {
        if (_closed || cancelled?.call() == true) {
          throw CoreFailure(
            'cancelled',
            'Documentation generation was cancelled',
          );
        }
      }

      if (preset == 'redoc' || preset == 'swagger') {
        final runtime = await DocumentationRuntime.forEngine(
          engine,
          preset: preset,
        );
        active();
        final presentation = await _prepareDocumentationPresentation(
          captured,
          requestId: requestId,
          cancelled: cancelled,
        );
        active();
        final files = <String, List<int>>{
          ...await runtime.page(
            presentation.toJson(),
            labels: {...defaultDocumentationLabels, ...?labels},
          ),
        };
        active();
        String portable(String id) {
          final uri = Uri.parse(id);
          return uri.scheme == 'file' &&
                  p.isWithin(access.boundary, uri.toFilePath())
              ? './${p.relative(uri.toFilePath(), from: access.boundary)}'
              : 'resource:${textIdentity(id)}';
        }

        final identity = await textIdentityAsync(
          jsonEncode({
            'html': contentIdentity(files['index.html']!),
            'assets': runtime.identity,
          }),
        );
        final metadata = <String, Object?>{
          'version': 1,
          'operation': 'build-docs',
          'preset': preset,
          'root': portable(root),
          'snapshot': snapshot.sourceIdentity,
          'input': captured.checked['unsaved'] == true
              ? 'working-copy'
              : 'saved-source',
          'unsaved': captured.checked['unsaved'] == true,
          'producer': runtime.adapter['producer'],
          'producerVersion': runtime.adapter['version'],
          'adapter': runtime.adapter,
          'assets': runtime.identity,
          'engine': engine.assetIdentity,
          'entry': 'index.html',
          'outputIdentity': identity,
          'rangeEncoding': 'utf16-half-open-without-bom',
          'sources': [
            for (final resource
                in snapshot.resources.toList()..sort(
                  (a, b) => (a['id'] as String).compareTo(b['id'] as String),
                ))
              {
                'resource': portable(resource['id'] as String),
                'identity': resource['identity'],
                'hasBom': resource['hasBom'] == true,
              },
          ],
          'derivedRepresentation':
              'graph-addressed-display-only (not an OpenAPI bundle)',
          'displayProducer': 'busyapi-reference-display',
          'displayProducerVersion': '1',
          'derivedIdentity': presentation.identity,
          'derivedProvenance': _portableDerivedProvenance(
            presentation.sourceProvenance,
            portable,
            'index.html',
          ),
        };
        files['provenance.json'] = utf8.encode('${jsonEncode(metadata)}\n');
        files['README.txt'] = utf8.encode(
          'BusyAPI local Redoc CE reference\n\nOpen index.html directly in a browser, including after relocating this whole directory. No server, BusyAPI, Node/npm, vendor account, CDN or Internet access is required. Keep all local files together, including THIRD_PARTY_NOTICES.txt and third-party.json.\n\nThis is read-only documentation of the captured ${metadata['input']}. Requests, authorization, telemetry and remote resource loading are disabled. Source provenance is in provenance.json; source files were not modified. This does not establish runtime conformance or API security.\n',
        );
        active();
        return DocumentationOutput._(
          this,
          captured,
          {
            'producer': runtime.adapter['producer'],
            'producerVersion': runtime.adapter['version'],
            'output': {'identity': identity},
          },
          metadata,
          files,
        );
      }

      final document = await engine.request(
        'referenceDocument',
        snapshot.toJson(),
        requestId: requestId == null ? null : '$requestId-document',
      );
      active();
      String portable(String id) {
        final uri = Uri.parse(id);
        if (uri.scheme == 'file' &&
            p.isWithin(access.boundary, uri.toFilePath())) {
          return './${p.relative(uri.toFilePath(), from: access.boundary)}';
        }
        return 'resource:${textIdentity(id)}';
      }

      final sources = [
        for (final resource
            in snapshot.resources.toList()..sort(
              (a, b) => (a['id'] as String).compareTo(b['id'] as String),
            ))
          {
            'resource': portable(resource['id'] as String),
            'identity': resource['identity'],
            'hasBom': resource['hasBom'] == true,
          },
      ];
      final rendered = await _renderReferenceDocument(document, snapshot, {
        for (final resource in snapshot.resources)
          resource['id'] as String: portable(resource['id'] as String),
      }, active);
      final html = rendered.html;
      active();
      final identity = await textIdentityAsync(html);
      final metadata = <String, Object?>{
        'version': 1,
        'operation': 'build-docs',
        'preset': preset,
        'root': portable(root),
        'snapshot': snapshot.sourceIdentity,
        'input': captured.checked['unsaved'] == true
            ? 'working-copy'
            : 'saved-source',
        'unsaved': captured.checked['unsaved'] == true,
        'producer': document['producer'],
        'producerVersion': document['producerVersion'],
        'engine': engine.assetIdentity,
        'entry': 'index.html',
        'outputIdentity': identity,
        'markdown': '7.3.1',
        'rangeEncoding': 'utf16-half-open-without-bom',
        'sources': sources,
        'provenance': rendered.provenance,
      };
      final files = await _encodeDocumentationFiles(html, metadata);
      active();
      if (files.values.any((bytes) => bytes.length > 16 * 1024 * 1024)) {
        throw CoreFailure(
          'limit.documentation.output',
          'Documentation exceeds the safe per-file output limit',
        );
      }
      return DocumentationOutput._(
        this,
        captured,
        {
          'producer': document['producer'],
          'producerVersion': document['producerVersion'],
          'output': {'identity': identity},
        },
        metadata,
        files,
      );
    } on CoreFailure catch (failure) {
      captured.access.close();
      if (failure is OutputAnalysisFailure) rethrow;
      throw OutputAnalysisFailure(
        failure.code,
        failure.message,
        captured.checked,
        cause: failure,
      );
    } on Object {
      captured.access.close();
      throw OutputAnalysisFailure(
        'io.failure',
        'Documentation generation did not complete; source files were not changed',
        captured.checked,
      );
    }
  }
}

List<Map<String, Object?>> _portableDerivedProvenance(
  Iterable entries,
  String Function(String) portable,
  String derivedResource,
) => [
  for (final entry in entries)
    {
      'source': {
        'resource': portable(entry['source']['resource'] as String),
        'pointer': entry['source']['pointer'],
        if ((entry['source'] as Map).containsKey('physicalPointer'))
          'physicalPointer': entry['source']['physicalPointer'],
        if ((entry['source'] as Map).containsKey('range'))
          'range': entry['source']['range'],
        if ((entry['source'] as Map).containsKey('occurrenceRange'))
          'occurrenceRange': entry['source']['occurrenceRange'],
      },
      'derived': {
        'resource': derivedResource,
        'pointer': entry['derived']['pointer'],
      },
      'kind': entry['kind'],
      if (entry['connection'] is String) 'connection': entry['connection'],
    },
];

String _referenceAnchor(Map location) =>
    's-${textIdentity(jsonEncode([location['resource'], location['pointer']]))}';
Map<String, Object?> _portableLocation(
  Map location,
  String Function(String) portable,
) => {
  'resource': portable(location['resource'] as String),
  'pointer': location['pointer'],
  'range': location['range'],
  if (location['physicalPointer'] != null)
    'physicalPointer': location['physicalPointer'],
  if (location['occurrenceRange'] != null)
    'occurrenceRange': location['occurrenceRange'],
};

void _verifyReferenceDocument(
  Map<String, dynamic> document,
  AnalysisSnapshot snapshot,
) {
  Never invalid() => throw CoreFailure(
    'documentation.protocol',
    'The worker returned malformed or incomplete original-source documentation',
  );
  if (document['version'] != 1 ||
      document['producer'] != 'busyapi-native-reference' ||
      document['producerVersion'] != '1' ||
      document['root'] != snapshot.root ||
      document['snapshot'] != snapshot.identity ||
      document['complete'] != true ||
      document['sections'] is! List ||
      (document['sections'] as List).length > 40000)
    invalid();
  final resources = {
    for (final resource in snapshot.resources) resource['id']: resource,
  };
  bool range(Object? value, int length) =>
      value is List &&
      value.length == 2 &&
      value[0] is int &&
      value[1] is int &&
      (value[0] as int) >= 0 &&
      (value[1] as int) >= (value[0] as int) &&
      (value[1] as int) <= length;
  bool located(Object? value) {
    if (value is! Map ||
        value['resource'] is! String ||
        value['pointer'] is! String)
      return false;
    final source = resources[value['resource']];
    if (source == null || value['generation'] != source['generation'])
      return false;
    final length = (source['text'] as String).length;
    return range(value['range'], length) &&
        (value['physicalPointer'] == null ||
            value['physicalPointer'] is String &&
                range(value['occurrenceRange'], length));
  }

  final identities = <String>{};
  final kinds = <String, String>{};
  final operationContexts = <String>{};
  final operationNavigationIds = <String>{};
  var bytes = 0, fields = 0, contextCount = 0, effectiveEntries = 0;
  Iterable<List> effectiveGroups(Map section) sync* {
    yield section['effective'] as List;
    for (final context in section['contexts'] as List? ?? const []) {
      yield context['effective'] as List;
    }
  }

  for (final section in document['sections'] as List) {
    if (section is! Map ||
        !located(section['source']) ||
        section['kind'] is! String ||
        section['entries'] is! List ||
        section['references'] is! List ||
        section['usages'] is! List ||
        section['effective'] is! List ||
        section['defaults'] is! List ||
        section['retrieval'] is! String ||
        !identities.add(_referenceAnchor(section['source'] as Map)))
      invalid();
    kinds[_referenceAnchor(section['source'] as Map)] =
        section['kind'] as String;
    for (final field in section['entries'] as List) {
      if (++fields > 200000 ||
          field is! Map ||
          field['name'] is! String ||
          field['kind'] is! String ||
          !located(field['source']) ||
          field['target'] != null && !located(field['target']) ||
          field['text'] != null && field['text'] is! String ||
          field['richText'] != null && field['richText'] is! bool)
        invalid();
      bytes += (field['text'] as String? ?? '').length * 2;
    }
    if (section['text'] != null && section['text'] is! String) invalid();
    bytes += (section['text'] as String? ?? '').length * 2;
    for (final reference in section['references'] as List) {
      if (reference is! Map ||
          reference['keyword'] is! String ||
          reference['value'] is! String ||
          !located(reference['source']) ||
          !located(reference['target']))
        invalid();
      if (reference['dynamic'] != null) {
        final dynamic = reference['dynamic'];
        if (dynamic is! Map ||
            dynamic['anchor'] is! String ||
            dynamic['candidates'] is! List ||
            !(dynamic['candidates'] as List).every(located))
          invalid();
      }
    }
    for (final usage in section['usages'] as List) {
      if (usage is! Map ||
          !located(usage['source']) ||
          usage['keyword'] is! String ||
          usage['dynamic'] is! bool)
        invalid();
    }
    if (section['contexts'] != null) {
      final contexts = section['contexts'];
      if (section['kind'] != 'operation' ||
          contexts is! List ||
          (contextCount += contexts.length) > 40000)
        invalid();
      for (final context in contexts) {
        if (context is! Map ||
            context['occurrence'] is! String ||
            context['navigationId'] is! String ||
            !RegExp(r'^[a-f0-9]{64}$')
                .hasMatch(context['navigationId'] as String) ||
            !operationNavigationIds.add(context['navigationId'] as String) ||
            !(context['occurrence'] as String).startsWith(
              '${snapshot.root}#/',
            ) ||
            (context['occurrence'] as String).length >
                snapshot.root.length + 16385 ||
            !operationContexts.add(context['occurrence'] as String) ||
            context['path'] is! String ||
            (context['path'] as String).length > 16384 ||
            context['method'] is! String ||
            (context['method'] as String).length > 256 ||
            !const [
              'operation',
              'webhook',
              'callback',
            ].contains(context['role']) ||
            !located(context['pathItem']) ||
            context['effective'] is! List ||
            (context['effective'] as List).length > 32)
          invalid();
        bytes +=
            (context['occurrence'] as String).length * 2 +
            (context['path'] as String).length * 2;
      }
    }
    for (final group in effectiveGroups(section)) {
      for (final field in group) {
        if (field is! Map ||
            field['name'] is! String ||
            field['source'] != null && !located(field['source']))
          invalid();
        if (field['ignored'] != null &&
            (field['ignored'] != true ||
                field['policy'] != 'oas30-http-method' ||
                field['method'] is! String ||
                (field['method'] as String).isEmpty ||
                !located(field['source'])))
          invalid();
        if (field['entries'] != null) {
          if (field['entries'] is! List ||
              field['count'] != (field['entries'] as List).length)
            invalid();
          for (final entry in field['entries'] as List) {
            if (++effectiveEntries > 400000 ||
                entry is! Map ||
                !located(entry['source']) ||
                entry['definition'] != null && !located(entry['definition']))
              invalid();
          }
        }
      }
    }
    if (bytes > 64 * 1024 * 1024) invalid();
  }
  if (!identities.contains(
    _referenceAnchor({'resource': snapshot.root, 'pointer': ''}),
  ))
    invalid();
  for (final section in document['sections'] as List) {
    for (final field in section['entries'] as List) {
      if (field['target'] != null &&
          !identities.contains(_referenceAnchor(field['target'] as Map)))
        invalid();
    }
    for (final reference in section['references'] as List) {
      if (!identities.contains(_referenceAnchor(reference['target'] as Map)))
        invalid();
      for (final target in reference['dynamic']?['candidates'] as List? ?? []) {
        if (!identities.contains(_referenceAnchor(target as Map))) invalid();
      }
    }
    for (final usage in section['usages'] as List) {
      if (!identities.contains(_referenceAnchor(usage['source'] as Map)))
        invalid();
    }
    for (final context in section['contexts'] as List? ?? const []) {
      if (kinds[_referenceAnchor(context['pathItem'] as Map)] != 'path-item')
        invalid();
    }
    for (final group in effectiveGroups(section as Map)) {
      for (final field in group) {
        if (field['source'] != null &&
            !identities.contains(_referenceAnchor(field['source'] as Map)))
          invalid();
        for (final entry in field['entries'] as List? ?? []) {
          if (!identities.contains(_referenceAnchor(entry['source'] as Map)))
            invalid();
        }
      }
    }
  }
}

int _activeDocumentationRenders = 0;

class _RenderedReferenceDocument {
  _RenderedReferenceDocument(this.html, this.provenance);
  final String html;
  final List<Map<String, Object?>> provenance;
}

Future<_RenderedReferenceDocument> _renderReferenceDocument(
  Map<String, dynamic> document,
  AnalysisSnapshot snapshot,
  Map<String, String> resources,
  void Function() active,
) => _runDocumentationWorker<_RenderedReferenceDocument>(_referenceHtmlWorker, [
  document,
  resources,
  snapshot,
], active);

// Two fixed data-only production entry points share admission, deadline and
// real exit ownership. This never accepts project code or executable rules.
Future<T> _runDocumentationWorker<T>(
  void Function(List<Object?>) entryPoint,
  List<Object?> data,
  void Function() active,
) async {
  if (_activeDocumentationRenders >= 2) {
    throw CoreFailure(
      'documentation.busy',
      'Documentation render capacity is full',
    );
  }
  _activeDocumentationRenders++;
  final port = ReceivePort(), exits = ReceivePort();
  final result = Completer<T>(), exited = Completer<void>();
  result.future.ignore();
  Isolate? worker;
  var released = false;
  void fail(String code) {
    if (!result.isCompleted)
      result.completeError(
        CoreFailure(code, 'Documentation rendering did not complete'),
      );
    worker?.kill(priority: Isolate.immediate);
  }

  final subscription = port.listen((message) {
    if (result.isCompleted) return;
    if (message is T) {
      result.complete(message);
    } else if (message is Map && message['code'] is String) {
      fail(message['code'] as String);
    } else {
      fail('documentation.worker');
    }
  });
  late StreamSubscription<dynamic> exitSubscription;
  exitSubscription = exits.listen((_) {
    if (!released) {
      released = true;
      _activeDocumentationRenders--;
    }
    if (!exited.isCompleted) exited.complete();
    unawaited(exitSubscription.cancel());
    exits.close();
  });
  final deadline = Timer(
    const Duration(seconds: 20),
    () => fail('documentation.timeout'),
  );
  final cancellation = Timer.periodic(const Duration(milliseconds: 25), (_) {
    try {
      active();
    } on Object {
      fail('cancelled');
    }
  });
  try {
    worker = await Isolate.spawn(
      entryPoint,
      [port.sendPort, ...data],
      onError: port.sendPort,
      onExit: exits.sendPort,
      errorsAreFatal: true,
    );
    active();
    return await result.future;
  } on Object {
    if (worker == null && !released) {
      released = true;
      _activeDocumentationRenders--;
      await exitSubscription.cancel();
      exits.close();
    }
    rethrow;
  } finally {
    deadline.cancel();
    cancellation.cancel();
    worker?.kill(priority: Isolate.immediate);
    try {
      if (worker != null) {
        // Retain admission until actual exit even if teardown itself times out.
        await exited.future.timeout(
          const Duration(seconds: 2),
          onTimeout: () {
            throw CoreFailure(
              'documentation.worker.stop',
              'The documentation worker did not acknowledge termination',
            );
          },
        );
      }
    } finally {
      await subscription.cancel();
      port.close();
    }
  }
}

void _referenceHtmlWorker(List<Object?> input) {
  final port = input[0] as SendPort;
  try {
    final resources = input[2] as Map<String, String>;
    final document = input[1] as Map<String, dynamic>;
    _verifyReferenceDocument(document, input[3] as AnalysisSnapshot);
    final html = _referenceHtml(input[1] as Map, (id) => resources[id]!);
    final provenance = <Map<String, Object?>>[
      for (final section in document['sections'] as List)
        {
          'source': _portableLocation(
            section['source'] as Map,
            (id) => resources[id]!,
          ),
          'derived': {
            'resource': 'index.html',
            'anchor': _referenceAnchor(section['source'] as Map),
          },
          'kind': section['kind'],
          'fields': [
            for (final field in section['entries'] as List)
              {
                'name': field['name'],
                'source': _portableLocation(
                  field['source'] as Map,
                  (id) => resources[id]!,
                ),
              },
          ],
          if (section['contexts'] is List)
            'contexts': [
              for (final context in section['contexts'] as List)
                {
                  'navigationId': context['navigationId'],
                  'path': context['path'],
                  'method': context['method'],
                  'role': context['role'],
                  'pathItem': _portableLocation(
                    context['pathItem'] as Map,
                    (id) => resources[id]!,
                  ),
                  'derived': {
                    'resource': 'index.html',
                    'anchor': 'operation-${context['navigationId']}',
                  },
                  'effective': [
                    for (final field in context['effective'] as List)
                      {
                        'name': field['name'],
                        'complete': field['complete'],
                        if (field['origin'] != null) 'origin': field['origin'],
                        if (field['source'] != null)
                          'source': _portableLocation(
                            field['source'] as Map,
                            (id) => resources[id]!,
                          ),
                        if (field['entries'] != null)
                          'entries': [
                            for (final entry in field['entries'] as List)
                              {
                                'source': _portableLocation(
                                  entry['source'] as Map,
                                  (id) => resources[id]!,
                                ),
                                if (entry['definition'] != null)
                                  'definition': _portableLocation(
                                    entry['definition'] as Map,
                                    (id) => resources[id]!,
                                  ),
                                'inherited': entry['inherited'],
                              },
                          ],
                      },
                  ],
                },
            ],
        },
    ];
    Isolate.exit(port, _RenderedReferenceDocument(html, provenance));
  } on Object catch (error) {
    port.send({
      'code': error is CoreFailure ? error.code : 'documentation.worker',
    });
  }
}

String _referenceHtml(Map document, String Function(String) portable) {
  const textEscape = HtmlEscape(HtmlEscapeMode.element);
  String escape(Object? value) => textEscape.convert(value?.toString() ?? '');
  String method(Object? value) =>
      const [
        'get',
        'put',
        'post',
        'delete',
        'options',
        'head',
        'patch',
        'trace',
        'query',
      ].contains(value)
      ? value.toString().toUpperCase()
      : value.toString();
  String contextLabel(Map value) =>
      '${method(value['method'])} ${value['path']} · ${value['role']}';
  String label(Map section) {
    final source = section['source'] as Map,
        pointer = source['pointer'] as String;
    final parts = pointer
        .split('/')
        .skip(1)
        .map((part) => part.replaceAll('~1', '/').replaceAll('~0', '~'))
        .toList();
    if (section['kind'] == 'root') return 'Overview';
    if (section['kind'] == 'operation') {
      final additional =
          parts.length > 1 && parts[parts.length - 2] == 'additionalOperations';
      final verb = method(parts.last),
          path = parts.take(parts.length - (additional ? 2 : 1)).join(' / ');
      return '$verb · $path';
    }
    return '${section['kind']} · ${parts.map((part) => part.isEmpty ? '""' : part).join(' / ')}';
  }

  final sections = (document['sections'] as List).cast<Map>();
  var title = 'API Reference';
  for (final section in sections.where(
    (section) =>
        section['kind'] == 'info' &&
        section['source']['resource'] == document['root'],
  )) {
    for (final field in section['entries'] as List)
      if (field['name'] == 'title' && field['text'] is String)
        title = field['text'] as String;
  }
  // The full authored title remains in its Info field. Avoid copying a huge
  // metadata scalar into browser chrome and the presentation heading as well.
  if (title.length > 240) {
    var end = 240;
    if (title.codeUnitAt(end - 1) >= 0xd800 &&
        title.codeUnitAt(end - 1) <= 0xdbff)
      end--;
    title = '${title.substring(0, end)}…';
  }
  final html = StringBuffer(
    '<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
    '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; style-src \'unsafe-inline\'; img-src \'none\'; connect-src \'none\'; frame-src \'none\'; object-src \'none\'; base-uri \'none\'; form-action \'none\'">'
    '<meta name="referrer" content="no-referrer"><title>${escape(title)}</title><style>'
    ':root{color-scheme:light dark;font-family:system-ui,sans-serif;line-height:1.5}body{margin:0 auto;max-width:100rem;padding:1.5rem}header,main,nav{min-width:0}h1,h2,h3{line-height:1.25}a{color:LinkText;overflow-wrap:anywhere}pre{white-space:pre-wrap;overflow-wrap:anywhere;padding:.8rem;border:1px solid GrayText;border-radius:.4rem}code{font-family:monospace}section{margin:2rem 0;padding-top:1rem;border-top:1px solid GrayText}dl{display:grid;grid-template-columns:minmax(6rem,12rem) minmax(0,1fr);gap:.7rem}dt{font-weight:600;overflow-wrap:anywhere}dd{margin:0;min-width:0}.source,small{font-size:.85rem;overflow-wrap:anywhere}blockquote{border-inline-start:3px solid GrayText;padding-inline-start:1rem}nav ul{columns:2;column-width:18rem;padding-inline-start:1.2rem}details{margin:.6rem 0}summary{cursor:pointer}p{overflow-wrap:anywhere}@media(max-width:40rem){dl{display:block}dd{margin-bottom:1rem}}'
    '</style></head><body><header><h1>${escape(title)}</h1><p>OpenAPI ${escape(document['family'])} · Read-only native Reference · No requests or authentication execution</p>'
    '<p><a href="provenance.json">Source and snapshot provenance</a> · <a href="README.txt">Offline use</a> · <a href="NOTICE.txt">Notices</a></p></header><nav aria-label="API contents"><h2>Operations and definitions</h2><ul>',
  );
  for (final section in sections) {
    final contexts = section['contexts'] as List? ?? const [];
    if (contexts.isNotEmpty) {
      for (final context in contexts)
        html.write(
          '<li><a href="#operation-${context['navigationId']}">${escape(contextLabel(context as Map))}</a></li>',
        );
      continue;
    }
    if (section['kind'] == 'root' ||
        section['kind'] == 'operation' ||
        section['source']['pointer'].toString().startsWith('/components/') &&
            '/'.allMatches(section['source']['pointer'] as String).length ==
                3) {
      html.write(
        '<li><a href="#${_referenceAnchor(section['source'] as Map)}">${escape(label(section))}</a></li>',
      );
    }
  }
  html.write('</ul></nav><main>');
  for (final section in sections) {
    final source = section['source'] as Map;
    html.write(
      '<section id="${_referenceAnchor(source)}"><h2>${escape(label(section))}</h2><p class="source">Source: ${escape(portable(source['resource'] as String))} · ${escape(source['pointer'])} · UTF-16 ${escape(source['range'])} (half-open; BOM excluded)</p>',
    );
    if (section['text'] != null)
      html.write('<pre>${escape(section['text'])}</pre>');
    if (section['kind'] == 'schema')
      html.write(
        '<p><small>Authored schema constraints and composition are not flattened. readOnly/writeOnly annotations depend on request/response use; they do not unconditionally remove properties.</small></p>',
      );
    if ((section['entries'] as List).isNotEmpty) html.write('<dl>');
    for (final field in section['entries'] as List) {
      html.write(
        '<dt>${escape(field['name'] == '' ? '"" (empty name)' : field['name'])}</dt><dd>',
      );
      if (field['target'] != null) {
        html.write(
          '<a href="#${_referenceAnchor(field['target'] as Map)}">${escape(field['kind'])} — view authored content</a>',
        );
      } else if (field['richText'] == true) {
        ReferenceMarkdown parsed;
        try {
          parsed = ReferenceMarkdown.parseInWorker(
            field['text'] as String,
            base: Uri.tryParse(section['retrieval'] as String),
          );
        } on Object {
          parsed = ReferenceMarkdown([
            ReferenceMarkup('text', text: field['text'] as String),
          ], formatted: false);
        }
        if (!parsed.formatted)
          html.write(
            '<p><small>Description preserved as complete plain text within presentation limits.</small></p>',
          );
        html.write(parsed.toHtml());
      } else {
        html.write('<pre>${escape(field['text'])}</pre>');
      }
      html.write('</dd>');
    }
    if ((section['entries'] as List).isNotEmpty) html.write('</dl>');
    for (final reference in section['references'] as List) {
      html.write(
        '<p>${escape(reference['keyword'])}: <a href="#${_referenceAnchor(reference['target'] as Map)}">${escape(reference['value'])} — definition</a></p>',
      );
      if (reference['dynamic'] != null) {
        html.write(
          '<p>Dynamic anchor ${escape(reference['dynamic']['anchor'])}: static navigation target above; the runtime evaluation scope determines the actual target.</p><ul>',
        );
        for (final candidate in reference['dynamic']['candidates'] as List)
          html.write(
            '<li><a href="#${_referenceAnchor(candidate as Map)}">${escape(portable(candidate['resource'] as String))} · ${escape(candidate['pointer'])}</a></li>',
          );
        html.write('</ul>');
      }
    }
    void writeEffective(List fields) {
      for (final effective in fields) {
        html.write(
          '<details><summary>Effective ${escape(effective['name'])} — ${effective['origin'] == 'specification'
              ? 'specification default'
              : effective['inherited'] == true
              ? 'inherited'
              : 'local/authored'}</summary>',
        );
        if (effective['source'] != null) {
          final owner = effective['source'] as Map;
          html.write(
            '<p><a href="#${_referenceAnchor(owner)}">${escape(portable(owner['resource'] as String))} · ${escape(owner['pointer'])}</a></p>',
          );
        }
        if (effective['default'] != null)
          html.write(
            '<p>Specification default, not authored: <code>${escape(jsonEncode(effective['default']))}</code></p>',
          );
        if (effective['ignored'] == true)
          html.write(
            '<p>OpenAPI 3.0 consumers ignore this ${escape(effective['method'])} request-body declaration. The authored declaration is retained below.</p>',
          );
        for (final entry in effective['entries'] as List? ?? [])
          html.write(
            '<p><a href="#${_referenceAnchor((entry as Map)['source'] as Map)}">${escape(entry['name'])} (${escape(entry['location'])})</a> — ${entry['inherited'] == true ? 'inherited' : 'local'}</p>',
          );
        html.write('</details>');
      }
    }

    final contexts = section['contexts'] as List? ?? const [];
    if (contexts.isNotEmpty) {
      for (final context in contexts) {
        html.write(
          '<details id="operation-${context['navigationId']}" data-busyapi-operation-context="${context['navigationId']}"><summary>${escape(contextLabel(context as Map))}</summary><p>Effective values apply only to this logical operation occurrence. <a href="#${_referenceAnchor(context['pathItem'] as Map)}">Path Item owner</a>; <a href="#${_referenceAnchor(source)}">authored operation definition</a>.</p>',
        );
        writeEffective(context['effective'] as List);
        html.write('</details>');
      }
    } else {
      if (section['kind'] == 'operation')
        html.write(
          '<p>Authored operation definition. No active Path Item occurrence supplies API-level inheritance.</p>',
        );
      writeEffective(section['effective'] as List);
    }
    if ((section['usages'] as List).isNotEmpty) {
      html.write('<details><summary>Known semantic usages</summary><ul>');
      for (final usage in section['usages'] as List) {
        final owner = usage['source'] as Map;
        html.write(
          '<li><a href="#${_referenceAnchor(owner)}">${escape(portable(owner['resource'] as String))} · ${escape(owner['pointer'])}</a> — ${escape(usage['keyword'])}${usage['dynamic'] == true ? ' (dynamic evaluation context applies)' : ''}</li>',
        );
      }
      html.write('</ul></details>');
    }
    if ((section['defaults'] as List).isNotEmpty) {
      html.write(
        '<details><summary>Effective defaults — not authored</summary><dl>',
      );
      for (final field in section['defaults'] as List)
        html.write(
          '<dt>${escape(field['name'])}</dt><dd><code>${escape(jsonEncode(field['value']))}</code></dd>',
        );
      html.write('</dl></details>');
    }
    html.write('</section>');
  }
  html.write('</main></body></html>\n');
  final result = html.toString();
  if (result.length > 64 * 1024 * 1024)
    throw CoreFailure(
      'limit.documentation.html',
      'Documentation exceeds its bounded HTML output size',
    );
  // Attribute strings above are generated anchors or fixed local filenames;
  // authored links are emitted only by the shared safe CommonMark serializer.
  return result;
}
