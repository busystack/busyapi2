// A top-level data-only closure cannot accidentally capture the project,
// process handles or the UI owner in the isolate message's lexical context.
Future<Map<String, List<int>>> _encodeDocumentationFiles(
  String html,
  Map<String, Object?> metadata,
) => Isolate.run(
  () => <String, List<int>>{
    'index.html': utf8.encode(html),
    'provenance.json': utf8.encode('${jsonEncode(metadata)}\n'),
    'README.txt': utf8.encode(
      'BusyAPI native Reference\n\nOpen index.html directly in a browser. No server, BusyAPI, Node, CDN or Internet connection is required.\nDescriptions are untrusted CommonMark: HTML is text and images are alt text only. External links require an explicit click and may leave this local document. Relative links use the captured source display context; local file links are not enabled.\nSource ownership and exact snapshot identities are in provenance.json. This is derived documentation, not an editable contract or a runtime security/conformance result.\n',
    ),
    'NOTICE.txt': utf8.encode(
      'Generated by BusyAPI native Reference, Copyright 2026 BusyStack.\nThis preset redistributes no JavaScript runtime, third-party parser code, font, icon or renderer assets. It uses browser/system fonts. Contract content retains its original ownership and licensing.\n',
    ),
  },
);

/// Frozen output ownership and publication are the same as bundle output.
/// The native preset does not invoke a bundler or a renderer's parser.
class DocumentationOutput extends BundleOutput {
  DocumentationOutput._(
    BusyProject owner,
    _OutputInput input,
    Map<String, dynamic> result,
    Map<String, Object?> metadata,
    Map<String, List<int>> files,
  ) : _files = Map.unmodifiable({
        for (final entry in files.entries)
          entry.key:
              (entry.value is Uint8List
                      ? entry.value as Uint8List
                      : Uint8List.fromList(entry.value))
                  .asUnmodifiableView(),
      }),
      super._(
        owner,
        input.access,
        input.target,
        input.snapshot,
        input.saved,
        input.checked['unsaved'] == true,
        input.revision,
        result,
        metadata,
      );
  final Map<String, List<int>> _files;
  @override
  Future<OutputDirectoryResult> publish({
    String? replaceIdentity,
    bool Function()? cancelled,
    FutureOr<void> Function()? beforePublish,
    FutureOr<void> Function()? afterPublish,
  }) {
    if (_closed) {
      throw CoreFailure('output.closed', 'The frozen output owner is closed');
    }
    return _access.publishOutput(
      destination,
      _files,
      metadata,
      replaceIdentity: replaceIdentity,
      cancelled: cancelled,
      beforePublish: beforePublish,
      afterPublish: afterPublish,
    );
  }
}

class _CheckedInput {
  _CheckedInput(this.snapshot, this.revision, this.checked, this.saved);
  final AnalysisSnapshot snapshot;
  final int revision;
  final Map<String, dynamic> checked;
  final bool saved;
}

class _OutputInput extends _CheckedInput {
  _OutputInput(this.access, this.target, _CheckedInput checked)
    : super(checked.snapshot, checked.revision, checked.checked, checked.saved);
  final ProjectAccess access;
  final String target;
}

extension _OutputCapture on BusyProject {
  // Preview/presentation capture has no output destination or filesystem write
  // capability. Exports own that independent capability separately.
  Future<_CheckedInput> _captureCheckedInput(
    String root, {
    required String operation,
    bool saved = false,
    String? requestId,
    bool Function()? cancelled,
    void Function(String resource)? onResourceRefreshed,
  }) async {
    AnalysisSnapshot? frozen;
    int? revision;
    final checked = await check(
      root,
      saved: saved,
      requestId: requestId,
      cancelled: cancelled,
      onResourceRefreshed: onResourceRefreshed,
      onSnapshot: (snapshot) {
        frozen = snapshot;
        revision = _resourceRevision;
      },
    );
    final snapshot = frozen;
    if (snapshot == null || checked['contextSnapshot'] != snapshot.identity) {
      throw CoreFailure(
        '$operation.snapshot',
        'The checked root has no coherent frozen input',
      );
    }
    final sourced = <String, dynamic>{
      ...checked,
      'sourceSnapshot': snapshot.sourceIdentity,
    };
    if (checked['complete'] != true) {
      throw OutputAnalysisFailure(
        '$operation.incomplete',
        'Required analysis did not complete; no output was produced',
        sourced,
      );
    }
    if (checked['status'] == 'invalid') {
      throw OutputAnalysisFailure(
        '$operation.contract',
        'Repair validity errors before producing documentation',
        sourced,
      );
    }
    if (_closed || cancelled?.call() == true) {
      throw CoreFailure('cancelled', 'Output generation was cancelled');
    }
    return _CheckedInput(snapshot, revision!, sourced, saved);
  }

  Future<_OutputInput> _captureOutputInput(
    String root,
    String destination, {
    required String operation,
    bool saved = false,
    String? requestId,
    bool Function()? cancelled,
    void Function(String resource)? onResourceRefreshed,
  }) async {
    final absolute = p.normalize(p.absolute(destination));
    final outputAccess = await ProjectAccess.open(p.dirname(absolute));
    try {
      final target = p.join(outputAccess.boundary, p.basename(absolute));
      final captured = await _captureCheckedInput(
        root,
        operation: operation,
        saved: saved,
        requestId: requestId,
        cancelled: cancelled,
        onResourceRefreshed: onResourceRefreshed,
      );
      final snapshot = captured.snapshot;
      final sourcePaths = <String>{
        ...files,
        ...store.buffers.values.map((buffer) => buffer.path),
        p.join(access.boundary, 'busyapi.yaml'),
        for (final id in <String>[
          ...roots.map((root) => root.id),
          ...snapshot.resources.map((resource) => resource['id'] as String),
          for (final policy in _policyDependencies.values) ...policy,
        ])
          if (Uri.parse(id).scheme == 'file') Uri.parse(id).toFilePath(),
      };
      if (target == access.boundary ||
          sourcePaths.any((path) {
            final source = p.normalize(p.absolute(path));
            return source == target || p.isWithin(target, source);
          })) {
        throw CoreFailure(
          'output.source',
          'An output cannot replace a project or a directory containing source or rules',
        );
      }
      if (_closed || cancelled?.call() == true) {
        throw CoreFailure('cancelled', 'Output generation was cancelled');
      }
      return _OutputInput(outputAccess, target, captured);
    } on Object {
      outputAccess.close();
      rethrow;
    }
  }
}

