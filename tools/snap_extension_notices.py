#!/usr/bin/env python3
"""Verify the actual generated Snap extension scripts and retain their sources.

No vendor-code edits, downloads, dependency installs or filesystem cleanup.
Only the reviewed independent launcher scripts are distributed, not Snapcraft.
"""
import argparse
import hashlib
import json
from pathlib import Path
import difflib

ROOT = Path(__file__).resolve().parent.parent


def ordinary(root, relative):
    name = Path(relative)
    if name.is_absolute() or '..' in name.parts:
        raise RuntimeError('Invalid extension material path')
    target = root / name
    if any(item.is_symlink() for item in [target, *target.parents] if item == root or root in item.parents):
        raise RuntimeError('Linked extension material')
    if not target.is_file() or target.stat().st_size > 1024 * 1024:
        raise RuntimeError('Missing or oversized extension material: ' + relative)
    return target.read_bytes()


def assemble(extensions, prime, *, review=None, license_file=None, publish=True):
    review = review or json.loads((ROOT / 'tools/snap_extensions.lock.json').read_text())
    license_file = license_file or ROOT / 'tools/licenses/snapcraft-command-chain/LICENSE'
    extensions, prime = extensions.resolve(strict=True), prime.resolve(strict=True)
    licence = ordinary(license_file.parent, license_file.name)
    if hashlib.sha256(licence).hexdigest() != review['licenseSha256']:
        raise RuntimeError('Changed original Snapcraft licence material')
    materials, records = {'LICENSE': licence}, []
    for item in review['files']:
        data = ordinary(extensions, item['file'])
        if hashlib.sha256(data).hexdigest() != item['sha256']:
            raise RuntimeError('Unreviewed Snapcraft extension source: ' + item['file'])
        parts = Path(item['file']).parts
        destination = 'sources/' + parts[0] + '/' + parts[-1]
        if destination in materials:
            raise RuntimeError('Repeated extension material')
        materials[destination] = data
        records.append({'file': destination, 'sha256': item['sha256']})
        if item.get('runtime'):
            expected = data.replace(b'%GPU_INTERFACE%', b'gpu-2404') if item.get('substituteGpu') else data
            if ordinary(prime, item['runtime']) != expected:
                raise RuntimeError('Unreviewed generated Snap extension: ' + item['runtime'])
    inventory = {key: review[key] for key in ['version', 'component', 'componentVersion', 'license', 'source']}
    inventory.update(purpose='Separate executable extension launch scripts, not linked application code',
        distribution='Only the extension scripts and complete corresponding template/Makefile sources; not the Snapcraft tool', files=records)
    materials['inventory.json'] = (json.dumps(inventory, sort_keys=True, indent=2) + '\n').encode()
    materials['MODIFICATIONS.txt'] = (
        'The GPU launcher is generated by the original supplied Makefile with GPU_INTERFACE=gpu-2404.\n'
        'This replaces the %GPU_INTERFACE% configuration token in the generated script only.\n'
        'Original templates, Makefiles and other launcher sources are retained unchanged beside this notice.\n'
        'These separate GPL-3.0 launcher scripts do not change BusyAPI application-source licensing.\n'
    ).encode()
    output = prime / 'share/licenses/busyapi-snap-extension'
    if not publish:
        return inventory
    # Verify every existing destination before writing any new material. Never
    # overwrite a different file or follow an escaping output-directory link.
    for relative, data in materials.items():
        target = output / relative
        if any(item.is_symlink() for item in [target, *target.parents] if item == prime or prime in item.parents):
            raise RuntimeError('Linked extension notice destination')
        if target.exists() and (not target.is_file() or target.read_bytes() != data):
            raise RuntimeError('Extension notice collision')
    for relative, data in materials.items():
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists():
            with target.open('xb') as stream:
                stream.write(data)
            target.chmod(0o644)
        if ordinary(output, relative) != data:
            raise RuntimeError('Assembled extension notice mismatch')
    return inventory


def collect_review(extensions, prime, destination, *, builder_version, source,
                   license_file=None, review=None):
    """An explicit review proposal, never implicit acceptance by a build.

    The selected builder must already have generated the runtime files. This
    verifies source/output correspondence and records original material; it
    does not rewrite launcher code, the maintained lock, or installed notices.
    """
    current = review or json.loads((ROOT / 'tools/snap_extensions.lock.json').read_text())
    licence = license_file or ROOT / 'tools/licenses/snapcraft-command-chain/LICENSE'
    if not builder_version or not source.startswith('https://'):
        raise RuntimeError('Identify the selected builder version and original upstream source URL')
    candidate = {**current, 'componentVersion': builder_version, 'source': source,
        'licenseSha256': hashlib.sha256(ordinary(licence.parent, licence.name)).hexdigest(),
        'files': [{**item, 'sha256': hashlib.sha256(ordinary(extensions, item['file'])).hexdigest()}
                  for item in current['files']]}
    assemble(extensions, prime, review=candidate, license_file=licence, publish=False)
    old = json.dumps(current, sort_keys=True, indent=2) + '\n'
    new = json.dumps(candidate, sort_keys=True, indent=2) + '\n'
    with Path(destination).open('x') as target:
        target.write(new)
    return ''.join(difflib.unified_diff(old.splitlines(True), new.splitlines(True),
        fromfile='reviewed extension materials', tofile='proposed extension materials'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--extensions', type=Path, required=True)
    parser.add_argument('--prime', type=Path, required=True)
    parser.add_argument('--collect-review', type=Path, help='Write a new review proposal; never update the maintained lock automatically')
    parser.add_argument('--builder-version')
    parser.add_argument('--source')
    parser.add_argument('--license-file', type=Path)
    args = parser.parse_args()
    if args.collect_review:
        print(collect_review(args.extensions, args.prime, args.collect_review,
            builder_version=args.builder_version, source=args.source or '', license_file=args.license_file))
    else:
        if args.builder_version or args.source or args.license_file:
            parser.error('Material identity overrides apply only to an explicit review proposal')
        assemble(args.extensions, args.prime)
